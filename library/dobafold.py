"""Title folding shared by the converter and the device (src/doba_fold_table.h).

The device has no Unicode database, so the rules are a small explicit table:
lower case, accents dropped (é -> e, ё -> е), punctuation to spaces, spaces
collapsed. `python3 dobafold.py --emit-c PATH` writes the table the firmware
compiles; both sides then fold every title identically.
"""
import sys
import unicodedata

KEY_BYTES = 56


def _map_cp(cp):
    """cp -> cp it folds to (0x20 = becomes a space), for the table range."""
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if cat[0] in "PSZC":
        return 0x20
    special = {"ё": "е", "Ё": "е", "ø": "o", "Ø": "o", "đ": "d", "Đ": "d",
               "ł": "l", "Ł": "l", "ı": "i", "ħ": "h", "Ħ": "h"}
    if ch in special:
        return ord(special[ch])
    low = ch.lower()
    if len(low) != 1:
        low = ch
    base = unicodedata.normalize("NFKD", low)
    if base and unicodedata.category(base[0])[0] == "L":
        return ord(base[0])
    return ord(low)


TABLE_RANGES = [(0x80, 0x250), (0x370, 0x400), (0x400, 0x530)]
TABLE = {}
for lo, hi in TABLE_RANGES:
    for cp in range(lo, hi):
        m = _map_cp(cp)
        if m != cp:
            TABLE[cp] = m


def fold_cp(cp):
    if cp < 0x80:
        c = chr(cp)
        if "0" <= c <= "9" or "a" <= c <= "z":
            return cp
        if "A" <= c <= "Z":
            return cp + 32
        return 0x20
    if 0x2000 <= cp < 0x2070:
        return 0x20
    return TABLE.get(cp, cp)


def fold(s, limit=KEY_BYTES - 1):
    out = []
    for ch in s:
        out.append(chr(fold_cp(ord(ch))))
    t = " ".join("".join(out).split())
    b = t.encode("utf-8")
    if len(b) > limit:
        b = b[:limit].decode("utf-8", "ignore").encode("utf-8").rstrip(b" ")
    return b


def emit_c(path):
    items = sorted(TABLE.items())
    with open(path, "w") as f:
        f.write("// Generated by library/dobafold.py --emit-c — do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("static const uint16_t kFoldFrom[%d] = {\n" % len(items))
        for i in range(0, len(items), 12):
            f.write("    " + ", ".join("0x%04X" % k for k, _ in items[i:i + 12]) + ",\n")
        f.write("};\nstatic const uint16_t kFoldTo[%d] = {\n" % len(items))
        for i in range(0, len(items), 12):
            f.write("    " + ", ".join("0x%04X" % v for _, v in items[i:i + 12]) + ",\n")
        f.write("};\nstatic const int kFoldCount = %d;\n" % len(items))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--emit-c":
        emit_c(sys.argv[2])
        print(len(TABLE), "entries")
    else:
        for a in sys.argv[1:]:
            print(repr(fold(a).decode()))
