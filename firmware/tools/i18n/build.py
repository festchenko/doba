#!/usr/bin/env python3
"""tools/i18n/uk.tsv -> src/doba_i18n_uk.inc (sorted by the English, as
strcmp sorts bytes). Checks that every Ukrainian keeps the English's %
specifiers in order (plural rows: each form).

uk.tsv: one row per string, English <TAB> Ukrainian; C escapes (\\xC2\\xB7,
\\n) as in the source; '#' starts a comment line. Plurals: the English
singular as key, "one|few|many" as the Ukrainian.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = re.compile(r"%[-+ #0-9.*]*[hlLzjt]*[diouxXfFeEgGcsp%]")


def unescape(s):
    """C escapes as the compiler reads them: \\xHH are bytes, \\uXXXX a char."""
    out, i = bytearray(), 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "x":
                j = i + 2
                while j < len(s) and j < i + 4 and s[j] in "0123456789abcdefABCDEF":
                    j += 1
                out.append(int(s[i + 2:j], 16)); i = j; continue
            if n == "u":
                out += chr(int(s[i + 2:i + 6], 16)).encode("utf-8"); i += 6; continue
            out += {"n": b"\n", "t": b"\t", '"': b'"', "\\": b"\\"}.get(n, n.encode()); i += 2; continue
        out += c.encode("utf-8"); i += 1
    return out.decode("utf-8")


def c_lit(s):
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    rows, bad = {}, 0
    for n, line in enumerate(open(os.path.join(HERE, "uk.tsv"), encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            print(f"uk.tsv:{n}: no tab", file=sys.stderr); bad += 1; continue
        en, uk = line.split("\t", 1)
        en, uk = unescape(en), unescape(uk)
        want = SPEC.findall(en)
        for form in uk.split("|"):
            if SPEC.findall(form) != want:
                print(f"uk.tsv:{n}: specifiers differ: {en!r} -> {form!r}", file=sys.stderr); bad += 1
        if en in rows and rows[en] != uk:
            print(f"uk.tsv:{n}: twice: {en!r}", file=sys.stderr); bad += 1
        rows[en] = uk
    if bad:
        sys.exit(1)
    keys = sorted(rows, key=lambda k: k.encode("utf-8"))
    with open(os.path.join(HERE, "..", "..", "src", "doba_i18n_uk.inc"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/i18n/build.py from tools/i18n/uk.tsv — do not edit.\n")
        f.write("static const Entry kUk[] = {\n")
        for k in keys:
            f.write(f"    {{{c_lit(k)}, {c_lit(rows[k])}}},\n")
        f.write("};\nstatic const size_t kUkCount = sizeof kUk / sizeof kUk[0];\n")
    print(f"{len(keys)} strings")


if __name__ == "__main__":
    main()
