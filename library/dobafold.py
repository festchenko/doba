"""Title folding shared by the converter and the device (src/doba_fold_table.h).

The device has no Unicode database, so the rules are a small explicit table:
lower case, accents dropped (é -> e, ё -> е), punctuation to spaces, spaces
collapsed. `python3 dobafold.py --emit-c PATH` writes the table the firmware
compiles; both sides then fold every title identically.
"""
import sys
import unicodedata

KEY_BYTES = 56


def _map_cp(cp):
    """cp -> cp it folds to (0x20 = becomes a space), for the table range."""
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if cat[0] in "PSZC":
        return 0x20
    special = {"ё": "е", "Ё": "е", "ø": "o", "Ø": "o", "đ": "d", "Đ": "d",
               "ł": "l", "Ł": "l", "ı": "i", "ħ": "h", "Ħ": "h"}
    if ch in special:
        return ord(special[ch])
    low = ch.lower()
    if len(low) != 1:
        low = ch
    base = unicodedata.normalize("NFKD", low)
    if base and unicodedata.category(base[0])[0] == "L":
        return ord(base[0])
    return ord(low)


TABLE_RANGES = [(0x80, 0x250), (0x370, 0x400), (0x400, 0x530)]
TABLE = {}
for lo, hi in TABLE_RANGES:
    for cp in range(lo, hi):
        m = _map_cp(cp)
        if m != cp:
            TABLE[cp] = m


def fold_cp(cp):
    if cp < 0x80:
        c = chr(cp)
        if "0" <= c <= "9" or "a" <= c <= "z":
            return cp
        if "A" <= c <= "Z":
            return cp + 32
        return 0x20
    if 0x2000 <= cp < 0x2070:
        return 0x20
    return TABLE.get(cp, cp)


def fold(s, limit=KEY_BYTES - 1):
    out = []
    for ch in s:
        out.append(chr(fold_cp(ord(ch))))
    t = " ".join("".join(out).split())
    b = t.encode("utf-8")
    if len(b) > limit:
        b = b[:limit].decode("utf-8", "ignore").encode("utf-8").rstrip(b" ")
    return b


# A key is at most 55 bytes. A longer folded title (a Wikisource chapter,
# "Твори (Франко, 1956–1962)/13/Захар Беркут/III", or any title past ~27
# Cyrillic letters) keeps its first 46 bytes, then \x01 and 8 letters of a
# hash of the whole fold (up to 240 bytes), so two long titles that start
# alike stay two keys. The device does the same (doba_library.cpp findIn).
KEY_MAX = KEY_BYTES - 1
LONG_CUT, LONG_FOLD = 46, 240
_B32 = "abcdefghijklmnopqrstuvwxyz234567"


def _cut(b, n):
    return b[:n].decode("utf-8", "ignore").encode("utf-8").rstrip(b" ")


def fnv1a64(b):
    h = 0xCBF29CE484222325
    for c in b:
        h = ((h ^ c) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def key(s):
    full = _cut(fold(s, 10 ** 6), LONG_FOLD)
    if len(full) <= KEY_MAX:
        return full
    h = fnv1a64(full)
    tag = "".join(_B32[(h >> (5 * i)) & 31] for i in range(8)).encode()
    return _cut(full, LONG_CUT) + b"\x01" + tag


def display(title, n=KEY_BYTES):
    """The title as lists show it, in n bytes: a path keeps its last parts
    ("Захар Беркут / III", volume numbers dropped); anything else is cut
    with an ellipsis."""
    t = " ".join(title.split())
    if len(t.encode("utf-8")) <= n:
        return t.encode("utf-8")
    parts = [p.strip() for p in t.split("/") if p.strip()]
    if len(parts) > 1:
        out = parts[-1]
        for p in reversed(parts[:-1]):
            if p.isdigit():
                continue
            cand = p + " / " + out
            if len(cand.encode("utf-8")) > n:
                break
            out = cand
        if len(out.encode("utf-8")) <= n:
            return out.encode("utf-8")
        t = out
    return _cut(t.encode("utf-8"), n - 3) + "\u2026".encode("utf-8")


def emit_c(path):
    items = sorted(TABLE.items())
    with open(path, "w") as f:
        f.write("// Generated by library/dobafold.py --emit-c — do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n\n")
        f.write("static const uint16_t kFoldFrom[%d] = {\n" % len(items))
        for i in range(0, len(items), 12):
            f.write("    " + ", ".join("0x%04X" % k for k, _ in items[i:i + 12]) + ",\n")
        f.write("};\nstatic const uint16_t kFoldTo[%d] = {\n" % len(items))
        for i in range(0, len(items), 12):
            f.write("    " + ", ".join("0x%04X" % v for _, v in items[i:i + 12]) + ",\n")
        f.write("};\nstatic const int kFoldCount = %d;\n" % len(items))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--emit-c":
        emit_c(sys.argv[2])
        print(len(TABLE), "entries")
    else:
        for a in sys.argv[1:]:
            print(repr(fold(a).decode()))
