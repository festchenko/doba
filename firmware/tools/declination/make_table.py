#!/usr/bin/env python3
"""Magnetic declination for the device: a 2-degree table over Europe from the
World Magnetic Model 2025 (pygeomag), for the middle of 2027 (it drifts about
0.1-0.2 deg a year; rebuild with a later --year).

    pip install pygeomag && python3 make_table.py > ../../src/doba_declination.h
"""
import argparse
import os

import pygeomag
from pygeomag import GeoMag

ap = argparse.ArgumentParser()
ap.add_argument("--year", type=float, default=2027.5)
a = ap.parse_args()
cof = os.path.join(os.path.dirname(pygeomag.__file__), "wmm", "WMM_2025.COF")
g = GeoMag(coefficients_file=cof)
LAT0, LAT1, LON0, LON1, STEP = 34, 72, -12, 44, 2
rows = []
for lat in range(LAT0, LAT1 + 1, STEP):
    rows.append([round(g.calculate(glat=lat, glon=lon, alt=0, time=a.year).d * 10)
                 for lon in range(LON0, LON1 + 1, STEP)])
print("#pragma once")
print("// Generated by tools/declination/make_table.py (WMM2025, %.1f) — do not edit." % a.year)
print("// Declination in tenths of a degree, east positive, every %d degrees." % STEP)
print("#include <cstdint>")
print("namespace decl_table {")
print("constexpr int LAT0 = %d, LAT1 = %d, LON0 = %d, LON1 = %d, STEP = %d;" % (LAT0, LAT1, LON0, LON1, STEP))
print("constexpr int NLAT = %d, NLON = %d;" % (len(rows), len(rows[0])))
print("static const int16_t kDecl[NLAT][NLON] = {")
for r in rows:
    print("    {" + ", ".join(str(v) for v in r) + "},")
print("};")
print("}  // namespace decl_table")
