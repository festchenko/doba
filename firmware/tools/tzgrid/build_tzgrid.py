#!/usr/bin/env python3
"""World time-zone grid for the device: position -> (standard offset, DST rule).

Doba has no network and no phone, so the clock's zone comes from where it is.
timezonefinder (OSM-derived boundaries, MIT) is sampled on a grid; each zone is
reduced to its standard offset and one of a few DST rules, worked out from
Python's zoneinfo. Output: src/tz_grid.h (run-length rows).

    pip install timezonefinder && python3 tools/tzgrid/build_tzgrid.py
"""
import datetime as dt
import sys
from zoneinfo import ZoneInfo

from timezonefinder import TimezoneFinder

STEP = 0.25            # degrees per cell
LAT0, LAT1 = -60.0, 80.0
RULES = {"NONE": 0, "EU": 1, "US": 2}


def classify(name):
    z = ZoneInfo(name)
    jan = dt.datetime(2026, 1, 15, 12, tzinfo=z).utcoffset()
    jul = dt.datetime(2026, 7, 15, 12, tzinfo=z).utcoffset()
    std = min(jan, jul)
    if jan == jul:
        return int(std.total_seconds() // 60), "NONE"
    # where does summer time start? EU: 01:00 UTC on the last Sunday of March.
    eu = dt.datetime(2026, 3, 29, 1, 30, tzinfo=dt.timezone.utc).astimezone(z).utcoffset()
    eu0 = dt.datetime(2026, 3, 29, 0, 30, tzinfo=dt.timezone.utc).astimezone(z).utcoffset()
    if eu != eu0:
        return int(std.total_seconds() // 60), "EU"
    us = dt.datetime(2026, 3, 8, 12, tzinfo=z).utcoffset()
    us0 = dt.datetime(2026, 3, 7, 12, tzinfo=z).utcoffset()
    if us != us0 and jul > jan:
        return int(std.total_seconds() // 60), "US"
    # Anything else (southern summers, odd dates): the offset in effect most of
    # the year, no switching. Off by an hour for part of the year there.
    return int(std.total_seconds() // 60), "NONE"


def main(out):
    tf = TimezoneFinder()
    zones, index, names = [], {}, {}
    rows = []
    nlat = int((LAT1 - LAT0) / STEP)
    nlon = int(360 / STEP)
    for j in range(nlat):
        lat = LAT0 + (j + 0.5) * STEP
        row = []
        for i in range(nlon):
            lon = -180 + (i + 0.5) * STEP
            name = tf.timezone_at(lat=lat, lng=lon) or "Etc/UTC"
            if name not in names:
                if name.startswith("Etc/GMT"):
                    # Etc/GMT+3 is UTC-3 (POSIX sign)
                    sign = -1 if "+" in name else 1
                    h = int(name[7:].lstrip("+-") or 0)
                    key = (sign * h * 60, "NONE", name.startswith("Europe/Kyiv"))
                else:
                    std, rule = classify(name)
                    key = (std, rule, name in ("Europe/Kyiv", "Europe/Kiev", "Europe/Simferopol",
                                              "Europe/Uzhgorod", "Europe/Zaporozhye"))
                if key not in index:
                    index[key] = len(zones)
                    zones.append(key)
                names[name] = index[key]
            row.append(names[name])
        rows.append(row)
        if j % 40 == 0:
            print(f"row {j}/{nlat}", file=sys.stderr)
    assert len(zones) < 256
    data, offs = bytearray(), []
    for row in rows:
        offs.append(len(data))
        i = 0
        while i < len(row):
            k = i
            while k < len(row) and row[k] == row[i] and k - i < 255:
                k += 1
            data += bytes([k - i, row[i]])
            i = k
    w = out.write
    w("#pragma once\n// Generated by tools/tzgrid/build_tzgrid.py — do not edit.\n")
    w("// Zone boundaries: timezonefinder (OpenStreetMap / timezone-boundary-builder, ODbL).\n")
    w("#include <cstdint>\nnamespace tz_grid {\n")
    w(f"constexpr float STEP = {STEP}f, LAT0 = {LAT0}f;\nconstexpr int NLAT = {nlat}, NLON = {nlon};\n")
    w("struct Zone { int16_t stdMin; uint8_t rule; uint8_t ukraine; };  // rule: 0 none, 1 EU, 2 US\n")
    w(f"const Zone kZones[{len(zones)}] = {{\n")
    for z in zones:
        w(f"    {{{z[0]}, {RULES[z[1]]}, {1 if z[2] else 0}}},\n")
    w("};\n")
    w(f"const uint32_t kRowOff[{len(offs)}] = {{\n")
    for i in range(0, len(offs), 12):
        w("    " + ", ".join(str(o) for o in offs[i:i + 12]) + ",\n")
    w("};\n")
    w(f"const uint8_t kRuns[{len(data)}] = {{  // (count, zone) pairs per row\n")
    for i in range(0, len(data), 24):
        w("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",\n")
    w("};\n}  // namespace tz_grid\n")
    print(f"{len(zones)} zones, {len(data)} bytes of runs", file=sys.stderr)


if __name__ == "__main__":
    main(open(sys.argv[1], "w") if len(sys.argv) > 1 else sys.stdout)
