"""make_inc.py: Doba's first-aid cards, built (build_aid.py) and put into the
firmware as bytes (firmware/src/doba_aid_books.inc). The firmware writes them
to the card when they are missing or differ, so the home page's first-aid bar
works on any card, and a new firmware brings new cards. Run after editing
cards_*.txt; the .inc is generated, never edited by hand."""
import os, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "firmware", "src", "doba_aid_books.inc")
books = [("aid_en", "cards_en.txt", "First aid", "en", "FIRST AID CARDS"),
         ("aid_uk", "cards_uk.txt", "Перша допомога", "uk", "КАРТКИ ПЕРШОЇ ДОПОМОГИ")]
files = []
with tempfile.TemporaryDirectory() as tmp:
    for d, src, name, lang, sec in books:
        out = os.path.join(tmp, d)
        subprocess.run([sys.executable, os.path.join(HERE, "build_aid.py"), os.path.join(HERE, src), out, name, lang, sec],
                       check=True, stdout=subprocess.DEVNULL)
        for f in ("index.dti", "a0000.dta", "info.txt", "menu.txt"):
            files.append((d + "/" + f, open(os.path.join(out, f), "rb").read()))
with open(OUT, "w") as o:
    o.write("// Generated by library/aid/make_inc.py from library/aid/cards_*.txt. Do not edit.\n")
    for i, (path, data) in enumerate(files):
        o.write(f"static const uint8_t kAid{i}[] = {{")
        for k, b in enumerate(data):
            o.write(("\n  " if k % 24 == 0 else "") + f"{b},")
        o.write("\n};\n")
    o.write("static const struct { const char* path; const uint8_t* data; size_t size; } kAidFiles[] = {\n")
    for i, (path, data) in enumerate(files):
        o.write(f'  {{"{path}", kAid{i}, sizeof kAid{i}}},\n')
    o.write("};\n")
print(f"{OUT}: {len(files)} files, {sum(len(d) for _, d in files)} bytes")
